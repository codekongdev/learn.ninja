import Link from "next/link"

import { Card } from "@workspace/ui/components/card"

import { getLesson, LESSON_SLUGS } from "@/lib/lessons"

export default function Page() {
  const lessons = LESSON_SLUGS.map((slug) => ({
    slug,
    lesson: getLesson(slug)!,
  }))
  return (
    <main className="mx-auto flex min-h-svh max-w-2xl flex-col gap-8 px-4 py-12">
      <header className="flex flex-col gap-2">
        <h1 className="text-3xl font-bold tracking-tight">Learn</h1>
        <p className="text-muted-foreground">
          Interactive lessons generated by your own LLM. These are the five test
          lessons, bundled while the player is being built.
        </p>
      </header>
      <ul className="grid gap-3">
        {lessons.map(({ slug, lesson }) => (
          <li key={slug}>
            <Card className="flex-row items-center justify-between gap-4 px-4 py-4">
              <Link
                href={`/lessons/${slug}`}
                className="flex min-w-0 flex-col gap-0.5 hover:underline"
              >
                <span className="font-semibold">{lesson.title}</span>
                <span className="text-sm text-muted-foreground">
                  {lesson.topic} · {lesson.estimatedMinutes} min
                </span>
              </Link>
              <Link
                href={`/lessons/${slug}?ui=ar`}
                className="shrink-0 text-sm text-muted-foreground hover:underline"
                lang="ar"
              >
                العربية
              </Link>
            </Card>
          </li>
        ))}
      </ul>
    </main>
  )
}
